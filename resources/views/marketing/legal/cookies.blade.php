<x-marketing.legal-page title="Política de Cookies">
    <p>Cookies e armazenamento local são pequenos dados guardados no seu navegador. Usamos apenas o necessário para o site funcionar — <strong>não usamos cookies de publicidade</strong>.</p>

    <h2>No site e no painel do restaurante</h2>
    <ul>
        <li><strong>Sessão</strong> — mantém você conectado ao painel.</li>
        <li><strong>Proteção de formulários (XSRF)</strong> — protege contra envios falsos.</li>
        <li><strong>Pagamento</strong> — ao assinar, a página de pagamento da Stripe usa os próprios cookies, necessários para processar o cartão com segurança.</li>
    </ul>

    <h2>No cardápio do restaurante</h2>
    <ul>
        <li><strong>Identificador de visita anônimo</strong> (armazenamento da sessão do navegador) — conta visualizações e tempo assistido por prato, sem identificar quem você é. É apagado ao fechar o navegador.</li>
        <li><strong>Dica de navegação</strong> (armazenamento local) — lembra que você já viu a dica “deslize para navegar”.</li>
        <li><strong>Cache do cardápio</strong> — capas e o primeiro vídeo ficam guardados para abrir mais rápido na próxima visita.</li>
    </ul>

    <h2>Como controlar</h2>
    <p>Você pode apagar cookies e dados do site nas configurações do navegador. Sem os cookies de sessão, não é possível entrar no painel.</p>
