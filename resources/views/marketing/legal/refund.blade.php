<x-marketing.legal-page title="Política de Reembolso">
    <h2>Direito de arrependimento</h2>
    <p>Na primeira contratação de um plano pago, você pode desistir em até <strong>7 dias</strong> e receber o valor pago de volta, conforme o art. 49 do Código de Defesa do Consumidor.</p>

    <h2>Assinaturas</h2>
    <ul>
        <li>Você pode cancelar a qualquer momento pelo painel, em <strong>Assinatura</strong>. Não há multa.</li>
        <li>Fora do prazo de arrependimento, o cancelamento interrompe as próximas cobranças; o mês já pago não é reembolsado proporcionalmente.</li>
        <li>Se a conta for excluída pelo dono, a assinatura é cancelada imediatamente.</li>
    </ul>

    <h2>Pacotes avulsos de gerações</h2>
    <ul>
        <li>Pacotes podem ser reembolsados em até 7 dias da compra, desde que as gerações não tenham sido usadas.</li>
        <li>Gerações que falharem por erro do provedor de inteligência artificial não são descontadas do saldo.</li>
    </ul>

    <h2>Cobranças indevidas</h2>
    <p>Se identificar uma cobrança que não reconhece ou duplicada, fale com a gente pelos <a href="{{ route('marketing.contact') }}">canais de contato</a>. O reembolso, quando aprovado, é feito no mesmo cartão usado na compra, e o prazo para aparecer na fatura depende do emissor do cartão.</p>
